# BOOKING
@app.route("/booking", methods=["GET", "POST"])
def booking():
    if "user_id" not in session:
        return redirect("/login")

    if request.method == "GET":
        session["booking_request_token"] = secrets.token_urlsafe(24)
        return render_template(
            "booking.html",
            request_token=session["booking_request_token"]
        )

    source = request.form.get("source")
    destination = request.form.get("destination")
    travel_date = request.form.get("travel_date")

    request_token = (
        request.form.get("request_token")
        or session.get("booking_request_token")
    )

    if not request_token:
        return "Booking session expired. Please reopen the booking page.", 400

    try:
        seats = int(request.form.get("seats"))
    except (ValueError, TypeError):
        return "Invalid seat selection.", 400

    if seats < 1 or seats > 6:
        return "You can book between 1 and 6 seats.", 400

    if source == destination:
        return "Source and destination cannot be the same.", 400

    try:
        selected_date = date.fromisoformat(travel_date)
        if selected_date < date.today():
            return "Please select a future date.", 400
    except (ValueError, TypeError):
        return "Invalid travel date.", 400

    fare = ROUTE_FARES.get((source, destination))
    if fare is None:
        fare = ROUTE_FARES.get((destination, source))

    if fare is None:
        return "Route not available.", 400

    total_fare = fare * seats
    ticket_code = secrets.token_urlsafe(24)

    try:
        with get_db() as conn:
            existing = conn.execute("""
                SELECT *
                FROM bookings
                WHERE request_token = %s AND user_id = %s
            """, (request_token, session["user_id"])).fetchone()

            if existing:
                return render_template(
                    "confirmation.html",
                    booking_id=existing["id"],
                    source=existing["source"],
                    destination=existing["destination"],
                    travel_date=existing["travel_date"],
                    seats=existing["seats"],
                    fare_per_seat=existing["total_fare"] // existing["seats"],
                    total_fare=existing["total_fare"],
                    ticket_code=existing["ticket_code"]
                )

            inserted = conn.execute("""
                INSERT INTO bookings (
                    user_id, source, destination, travel_date,
                    seats, total_fare, status, ticket_code, request_token
                )
                VALUES (%s, %s, %s, %s, %s, %s, %s, %s, %s)
                RETURNING id
            """, (
                session["user_id"],
                source,
                destination,
                travel_date,
                seats,
                total_fare,
                "Confirmed",
                ticket_code,
                request_token
            )).fetchone()

            booking_id = inserted["id"]

    except UniqueViolation:
        # A repeated submission may race with an earlier request.
        with get_db() as conn:
            existing = conn.execute("""
                SELECT *
                FROM bookings
                WHERE request_token = %s AND user_id = %s
            """, (request_token, session["user_id"])).fetchone()

        if existing:
            return render_template(
                "confirmation.html",
                booking_id=existing["id"],
                source=existing["source"],
                destination=existing["destination"],
                travel_date=existing["travel_date"],
                seats=existing["seats"],
                fare_per_seat=existing["total_fare"] // existing["seats"],
                total_fare=existing["total_fare"],
                ticket_code=existing["ticket_code"]
            )

        return "Booking could not be completed. Please try again.", 400

    session.pop("booking_request_token", None)

    return render_template(
        "confirmation.html",
        booking_id=booking_id,
        source=source,
        destination=destination,
        travel_date=travel_date,
        seats=seats,
        fare_per_seat=fare,
        total_fare=total_fare,
        ticket_code=ticket_code
    )


# DOWNLOAD SECURE PDF TICKET
@app.route("/download_ticket/<int:booking_id>")
def download_ticket(booking_id):
    if "user_id" not in session:
        return redirect("/login")

    with get_db() as conn:
        booking_record = conn.execute("""
            SELECT *
            FROM bookings
            WHERE id = %s AND user_id = %s
        """, (
            booking_id,
            session["user_id"]
        )).fetchone()

    if booking_record is None:
        return "Booking not found or access denied.", 404

    if booking_record["status"] != "Confirmed":
        return "Cancelled tickets cannot be downloaded.", 400

    pdf_buffer = BytesIO()
    pdf = SimpleDocTemplate(pdf_buffer, pagesize=A4)

    styles = getSampleStyleSheet()
    content = [
        Paragraph("<b>CLOUDBUS</b>", styles["Title"]),
        Spacer(1, 20),
        Paragraph("<b>BUS TICKET CONFIRMATION</b>", styles["Heading2"]),
        Spacer(1, 20)
    ]

    details = [
        f"<b>Booking ID:</b> {booking_record['id']}",
        f"<b>Ticket Reference:</b> {booking_record['ticket_code']}",
        f"<b>From:</b> {booking_record['source']}",
        f"<b>Destination:</b> {booking_record['destination']}",
        f"<b>Travel Date:</b> {booking_record['travel_date']}",
        f"<b>Seats:</b> {booking_record['seats']}",
        f"<b>Fare Per Seat:</b> Rs. {booking_record['total_fare'] // booking_record['seats']}",
        f"<b>Total Fare:</b> Rs. {booking_record['total_fare']}",
        f"<b>Status:</b> {booking_record['status']}"
    ]

    for detail in details:
        content.append(Paragraph(detail, styles["Normal"]))
        content.append(Spacer(1, 12))

    content.append(Paragraph(
        "Thank you for choosing CloudBus!",
        styles["Italic"]
    ))

    pdf.build(content)
    pdf_buffer.seek(0)

    return send_file(
        pdf_buffer,
        as_attachment=True,
        download_name=f"CloudBus_Ticket_{booking_record['id']}.pdf",
        mimetype="application/pdf"
    )


# TICKET VERIFICATION
@app.route("/verify-ticket/<ticket_code>")
def verify_ticket(ticket_code):
    if not ticket_code or len(ticket_code) > 100:
        return render_template(
            "ticket_verification.html",
            valid=False,
            booking=None
        ), 404

    with get_db() as conn:
        booking_record = conn.execute("""
            SELECT
                ticket_code,
                source,
                destination,
                travel_date,
                seats,
                status
            FROM bookings
            WHERE ticket_code = %s
        """, (ticket_code,)).fetchone()

    if booking_record is None:
        return render_template(
            "ticket_verification.html",
            valid=False,
            booking=None
        ), 404

    is_valid = booking_record["status"] == "Confirmed"

    return render_template(
        "ticket_verification.html",
        valid=is_valid,
        booking=booking_record
    )


