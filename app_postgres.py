# DATABASE CONNECTION
@contextmanager
def get_db():
    if not DATABASE_URL:
        raise RuntimeError("DATABASE_URL is not set.")

    conn = psycopg.connect(
        DATABASE_URL,
        row_factory=dict_row,
        connect_timeout=10
    )

    try:
        with conn:
            yield conn
    finally:
        conn.close()


# DATABASE INITIALIZATION
def init_db():
    with get_db() as conn:
        conn.execute("""
            CREATE TABLE IF NOT EXISTS users (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                username TEXT NOT NULL,
                email TEXT UNIQUE NOT NULL,
                password TEXT NOT NULL,
                role TEXT DEFAULT 'user'
            )
        """)

        conn.execute("""
            CREATE TABLE IF NOT EXISTS bookings (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                user_id BIGINT REFERENCES users(id),
                source TEXT,
                destination TEXT,
                travel_date TEXT,
                seats INTEGER,
                total_fare INTEGER DEFAULT 0,
                status TEXT DEFAULT 'Confirmed',
                ticket_code TEXT,
                request_token TEXT
            )
        """)

        conn.execute("""
            CREATE UNIQUE INDEX IF NOT EXISTS idx_ticket_code
            ON bookings(ticket_code)
        """)

        conn.execute("""
            CREATE UNIQUE INDEX IF NOT EXISTS idx_bookings_request_token
            ON bookings(request_token)
        """)

        # Preserve an existing admin password; only ensure the role is admin.
        conn.execute("""
            INSERT INTO users (username, email, password, role)
            VALUES (%s, %s, %s, %s)
            ON CONFLICT (email)
            DO UPDATE SET role = 'admin'
        """, (
            "Admin",
            "admin@cloudbus.com",
            generate_password_hash("Admin@123"),
            "admin"
        ))


