import os
import sqlite3
import psycopg

# SQLite database
BASE_DIR = os.path.dirname(os.path.abspath(__file__))
SQLITE_DB = os.path.join(BASE_DIR, "database", "cloudbus.db")

# PostgreSQL connection
DATABASE_URL = os.environ.get("DATABASE_URL")

if not DATABASE_URL:
    raise RuntimeError("DATABASE_URL environment variable is missing.")

# Connect to SQLite
sqlite_conn = sqlite3.connect(SQLITE_DB)
sqlite_conn.row_factory = sqlite3.Row

# Connect to PostgreSQL
pg_conn = psycopg.connect(DATABASE_URL)

try:
    with pg_conn.cursor() as cur:

        # CREATE USERS TABLE
        cur.execute("""
            CREATE TABLE IF NOT EXISTS users (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                username TEXT NOT NULL,
                email TEXT UNIQUE NOT NULL,
                password TEXT NOT NULL,
                role TEXT DEFAULT 'user'
            )
        """)

        # CREATE BOOKINGS TABLE
        cur.execute("""
            CREATE TABLE IF NOT EXISTS bookings (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                user_id BIGINT REFERENCES users(id),
                source TEXT,
                destination TEXT,
                travel_date TEXT,
                seats INTEGER,
                total_fare INTEGER DEFAULT 0,
                status TEXT DEFAULT 'Confirmed',
                ticket_code TEXT,
                request_token TEXT
            )
        """)

        # UNIQUE INDEXES
        cur.execute("""
            CREATE UNIQUE INDEX IF NOT EXISTS idx_ticket_code
            ON bookings(ticket_code)
        """)

        cur.execute("""
            CREATE UNIQUE INDEX IF NOT EXISTS idx_bookings_request_token
            ON bookings(request_token)
        """)

        # READ SQLITE USERS
        users = sqlite_conn.execute(
            "SELECT * FROM users"
        ).fetchall()

        for user in users:
            cur.execute("""
                INSERT INTO users
                (id, username, email, password, role)
                VALUES (%s, %s, %s, %s, %s)
                ON CONFLICT (id) DO NOTHING
            """, (
                user["id"],
                user["username"],
                user["email"],
                user["password"],
                user["role"]
            ))

        # READ SQLITE BOOKINGS
        bookings = sqlite_conn.execute(
            "SELECT * FROM bookings"
        ).fetchall()

        for booking in bookings:
            cur.execute("""
                INSERT INTO bookings (
                    id, user_id, source, destination,
                    travel_date, seats, total_fare,
                    status, ticket_code, request_token
                )
                VALUES (%s, %s, %s, %s, %s, %s, %s, %s, %s, %s)
                ON CONFLICT (id) DO NOTHING
            """, (
                booking["id"],
                booking["user_id"],
                booking["source"],
                booking["destination"],
                booking["travel_date"],
                booking["seats"],
                booking["total_fare"],
                booking["status"],
                booking["ticket_code"],
                booking["request_token"]
            ))

        # UPDATE ID SEQUENCES
        cur.execute("""
            SELECT setval(
                pg_get_serial_sequence('users', 'id'),
                COALESCE((SELECT MAX(id) FROM users), 1),
                EXISTS(SELECT 1 FROM users)
            )
        """)

        cur.execute("""
            SELECT setval(
                pg_get_serial_sequence('bookings', 'id'),
                COALESCE((SELECT MAX(id) FROM bookings), 1),
                EXISTS(SELECT 1 FROM bookings)
            )
        """)

    pg_conn.commit()

    print("Migration completed successfully!")
    print(f"Users migrated: {len(users)}")
    print(f"Bookings migrated: {len(bookings)}")

except Exception:
    pg_conn.rollback()
    raise

finally:
    sqlite_conn.close()
    pg_conn.close()